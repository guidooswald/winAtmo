const LEGACY_THEME_MAP: Record<string, ThemeId> = {
  dark: 'fluent-dark',
  light: 'fluent-light',
  'catppuccin-mocha': 'fluent-dark',
  'catppuccin-latte': 'fluent-light',
  'tokyo-night': 'terminal-dark',
  dracula: 'fluent-dark',
  'oled-black': 'terminal-dark',
  'solarized-light': 'soft-light',
  'rose-pine-dawn': 'soft-light',
  'github-light': 'fluent-light',
  'nord-dark': 'nord-dark',
  'nord-light': 'nord-light',
};

export function getThemeDefinition(themeId?: string): ThemeDefinition {
  if (!themeId) return THEMES[0];
  const targetId = LEGACY_THEME_MAP[themeId] || themeId;
  return THEMES.find((t) => t.id === targetId) || THEMES[0];
}

export function applyThemeToDocument(themeId?: string): ThemeDefinition {
  const def = getThemeDefinition(themeId);
  if (typeof document !== 'undefined') {
    const root = document.documentElement;
    root.setAttribute('data-theme', def.id);
    root.setAttribute('data-theme-family', def.family);
    root.setAttribute('data-theme-mode', def.mode);
    root.style.colorScheme = def.mode;
    for (const [k, v] of Object.entries(def.vars)) {
      root.style.setProperty(k, v);
    }
    root.style.setProperty('--widget-bg-rgb', def.widgetBgRgb);
  }
  return def;
}

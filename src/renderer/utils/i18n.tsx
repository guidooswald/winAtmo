export const TRANSLATIONS: Record<LanguageId, Record<TranslationKey, string>> = {
  en: EN,
  de: DE,
  fr: FR,
  es: ES,
  pt: PT,
  it: IT,
  pl: PL,
  cs: CS,
  el: EL,
};

export interface I18nContextValue {
  language: LanguageId;
  definition: LanguageDefinition;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  formatNumber: (n: number, options?: Intl.NumberFormatOptions) => string;
  formatDate: (date: Date | number, options?: Intl.DateTimeFormatOptions) => string;
  formatTime: (date: Date | number, options?: Intl.DateTimeFormatOptions) => string;
}

const LanguageContext = createContext<I18nContextValue>({
  language: 'en',
  definition: LANGUAGES[0],
  t: (key: TranslationKey, params?: Record<string, string | number>) => {
    let str = EN[key] || String(key);
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  },
  formatNumber: (n: number) => n.toLocaleString(),
  formatDate: (d: Date | number) => new Date(typeof d === 'number' && d < 1e11 ? d * 1000 : d).toLocaleDateString(),
  formatTime: (d: Date | number) => new Date(typeof d === 'number' && d < 1e11 ? d * 1000 : d).toLocaleTimeString(),
});

export const LanguageProvider: React.FC<{
  language?: LanguageId;
  children: React.ReactNode;
}> = ({ language = 'en', children }) => {
  const activeLang: LanguageId = TRANSLATIONS[language] ? language : 'en';
  const definition = useMemo(
    () => LANGUAGES.find((l) => l.id === activeLang) || LANGUAGES[0],
    [activeLang]
  );

  const value = useMemo<I18nContextValue>(() => {
    const dict = TRANSLATIONS[activeLang] || EN;

    const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
      let str = dict[key] || EN[key] || String(key);
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return str;
    };

    const formatNumber = (n: number, options?: Intl.NumberFormatOptions): string => {
      try {
        return new Intl.NumberFormat(definition.locale, options).format(n);
      } catch {
        return n.toLocaleString();
      }
    };

    const formatDate = (date: Date | number, options?: Intl.DateTimeFormatOptions): string => {
      const d = typeof date === 'number' ? new Date(date < 1e11 ? date * 1000 : date) : date;
      try {
        return new Intl.DateTimeFormat(definition.locale, options).format(d);
      } catch {
        return d.toLocaleDateString();
      }
    };

    const formatTime = (date: Date | number, options?: Intl.DateTimeFormatOptions): string => {
      const d = typeof date === 'number' ? new Date(date < 1e11 ? date * 1000 : date) : date;
      try {
        return new Intl.DateTimeFormat(definition.locale, options || { hour: '2-digit', minute: '2-digit', second: '2-digit' }).format(d);
      } catch {
        return d.toLocaleTimeString();
      }
    };

    return {
      language: activeLang,
      definition,
      t,
      formatNumber,
      formatDate,
      formatTime,
    };
  }, [activeLang, definition]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export function useI18n(): I18nContextValue {
  return useContext(LanguageContext);
}
